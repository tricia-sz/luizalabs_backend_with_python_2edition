# Maiusculas, minusculas e titulo
curso = 'pYtHon'

print(curso.upper()) # PYTHON
print(curso.lower()) # python
print(curso.title()) # Python

print(curso.strip()) # Tira espaços em branco da esquerda e direita
print(curso.lstrip()) # Tira espaços em branco da esquerda
print(curso.rstrip()) # Tira espaços em branco  direita

print(curso.center(10, "*")) # *****Python*****
print("_".join(curso)) # P_y_t_h_o_n





